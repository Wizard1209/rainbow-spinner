"""Writes hooks/core/atlas.ts: the font masks a picture style draws its word with.

Printable ASCII (U+0020..U+007E), the Latin-1 letters U+00C0..U+00FF (the
engine's own words include Flambéing and Sautéing) and U+2026, each an 8-bit
alpha mask of one 25x48 pixel cell: a terminal cell at font size 20 on a
Retina screen, the size the bloom plant's two-cell pictures are drawn for.
The font is JetBrains Mono Regular 2.304 at 40 pixels, from
fonts/ttf/JetBrainsMono-Regular.ttf in
https://github.com/JetBrains/JetBrainsMono/releases/tag/v2.304. Its 24 pixel
advance starts one pixel from the cell's left edge, so the cell's spare pixel
column is on the left. The baseline is on row 39 from the top, so the accents
of the capitals stay inside the cell; ink outside the cell is clipped.

    uv run font/gen_atlas.py --font PATH/JetBrainsMono-Regular.ttf
"""
import argparse
import base64
import json
import math
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

CHARS = [chr(c) for c in range(0x20, 0x7F)] + [chr(c) for c in range(0xC0, 0x100)] + ["…"]
OUT = Path(__file__).resolve().parent.parent / "hooks" / "core" / "atlas.ts"
CELL_W, CELL_H, BASELINE, PX = 25, 48, 39, 40


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--font", required=True, help="path to JetBrainsMono-Regular.ttf")
    args = ap.parse_args()

    tt = TTFont(args.font)
    cmap = tt.getBestCmap()
    missing = [c for c in CHARS if ord(c) not in cmap]
    if missing:
        raise SystemExit(f"font lacks {missing!r}")
    upem = tt["head"].unitsPerEm
    advance = max(tt["hmtx"][cmap[ord(c)]][0] for c in CHARS) * PX / upem
    if advance > CELL_W:
        raise SystemExit(f"advance {advance} px is wider than the {CELL_W} px cell")
    pen = math.floor((CELL_W - advance) / 2 + 0.5)

    font = ImageFont.truetype(args.font, PX, layout_engine=ImageFont.Layout.BASIC)
    glyphs = {}
    for ch in CHARS:
        cell = Image.new("L", (CELL_W, CELL_H), 0)
        ImageDraw.Draw(cell).text((pen, BASELINE), ch, fill=255, font=font, anchor="ls")
        glyphs[ch] = base64.b64encode(cell.tobytes()).decode()

    name = tt["name"]
    meta = {
        "font": f"{name.getDebugName(4)} {name.getDebugName(5).split(';')[0].removeprefix('Version ')}",
        "px": PX,
        "baseline": BASELINE,
        "pen": pen,
    }
    OUT.write_text(
        "// Generated by font/gen_atlas.py; regenerate rather than edit.\n"
        f"// {json.dumps(meta, ensure_ascii=True)}\n"
        "// glyphs[ch]: base64 of cellW*cellH alpha bytes, row-major from the top-left.\n"
        f"export const cellW = {CELL_W};\n"
        f"export const cellH = {CELL_H};\n"
        f"export const glyphs: Record<string, string> = {json.dumps(glyphs, indent=1, ensure_ascii=True)};\n"
    )
    print(f"{OUT}: {meta['font']}, cell {CELL_W}x{CELL_H}, baseline {BASELINE}, pen x {pen}, {len(glyphs)} glyphs")


if __name__ == "__main__":
    main()
