"""Writes hooks/styles/bloom-sprites.ts: bloom's plant where the terminal has no Nerd glyphs.

Each stage is a Material Design icon from sprites/mdi/ rasterised into the
glyph's two cells, 50x48 pixels (two cells of hooks/core/atlas.ts), within a
36 px box at (4, 7) that leaves a gap before the word. The icons draw inside
the square from (2, 2) to (22, 22) of their 24-unit view box, so that square,
the same for all six, fills the box; the generator stops if an icon draws
outside it. A stage is stored as the Nerd Font codepoint of the same icon, its
pastel colour and an 8-bit coverage mask; the sprite is that colour at that
coverage.

    uv run sprites/gen_sprites.py
"""
import base64
import io
import json
import math
import re
from pathlib import Path

import resvg_py
from PIL import Image

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "hooks" / "styles" / "bloom-sprites.ts"
W, H, BOX, X0, Y0 = 50, 48, 36, 4, 7
# The square of the icons' 24-unit view box that fills the box: x, y, side.
VIEW = (2, 2, 20)

# stage: (icon, its Nerd Font codepoint, OKLCh lightness, chroma, hue):
# a warm seed, greens, a lilac lotus.
STAGES = {
    "seed": ("mdi/seed.svg", 0xF0E62, 0.78, 0.07, 75),
    "sprout": ("mdi/sprout.svg", 0xF0E66, 0.83, 0.11, 137),
    "leaf": ("mdi/leaf.svg", 0xF032A, 0.81, 0.11, 145),
    "clover": ("mdi/clover.svg", 0xF0816, 0.81, 0.11, 150),
    "palmate": ("mdi/palmate.svg", 0xF07A6, 0.80, 0.13, 150),
    "lotus": ("mdi/spa.svg", 0xF0CD1, 0.79, 0.10, 330),
}


def oklch(l: float, c: float, h: float) -> tuple[int, int, int]:
    def srgb(a: float, b: float) -> list[float]:
        lc = (l + 0.3963377774 * a + 0.2158037573 * b) ** 3
        mc = (l - 0.1055613458 * a - 0.0638541728 * b) ** 3
        sc = (l - 0.0894841775 * a - 1.2914855480 * b) ** 3
        rgb = (
            4.0767416621 * lc - 3.3077115913 * mc + 0.2309699292 * sc,
            -1.2684380046 * lc + 2.6097574011 * mc - 0.3413193965 * sc,
            -0.0041960863 * lc - 0.7034186147 * mc + 1.7076147010 * sc,
        )
        return [12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055 for v in rgb]

    # The chroma gives way where sRGB cannot hold it, so no channel clips.
    while True:
        rgb = srgb(c * math.cos(math.radians(h)), c * math.sin(math.radians(h)))
        if all(-1e-6 <= v <= 1 + 1e-6 for v in rgb) or c < 1e-3:
            return tuple(round(max(0, min(1, v)) * 255) for v in rgb)
        c *= 0.97


def render(svg: str, view: tuple[float, float, float], size: int) -> Image.Image:
    svg = re.sub(r'viewBox="[^"]*"', 'viewBox="{} {} {} {}"'.format(*view, view[2]), svg, count=1)
    png = resvg_py.svg_to_bytes(svg_string=svg, width=size, height=size)
    return Image.open(io.BytesIO(bytes(png))).convert("RGBA").getchannel("A")


def coverage(svg_path: Path) -> bytes:
    svg = re.sub(r"<svg\b", '<svg fill="#fff"', svg_path.read_text(), count=1)
    assert 'viewBox="0 0 24 24"' in svg, svg_path
    # At 10 px a unit the square's edges fall on pixel edges.
    x, y, side = VIEW
    left, top, right, bottom = render(svg, (0, 0, 24), 240).getbbox()
    assert x * 10 <= left and y * 10 <= top and right <= (x + side) * 10 and bottom <= (y + side) * 10, f"{svg_path} draws outside {VIEW}"
    icon = render(svg, VIEW, BOX * 8).resize((BOX, BOX), Image.Resampling.BOX)
    slot = Image.new("L", (W, H), 0)
    slot.paste(icon, (X0, Y0))
    return slot.tobytes()


def main() -> None:
    stages = {}
    for name, (icon, code, l, c, h) in STAGES.items():
        stages[name] = {"code": code, "rgb": list(oklch(l, c, h)), "alpha": base64.b64encode(coverage(HERE / icon)).decode()}
    OUT.write_text(
        "// Generated by sprites/gen_sprites.py; regenerate rather than edit.\n"
        "// Icons from Material Design Icons 7.4.47 (Apache-2.0), recoloured and\n"
        "// rasterised: see THIRD_PARTY.md.\n"
        "// code: the Nerd Font codepoint of the same icon, which bloom draws as text.\n"
        "// alpha: base64 of width*height coverage bytes, row-major from the top-left.\n"
        f"export const width = {W};\n"
        f"export const height = {H};\n"
        "export const sprites = {\n"
        + "".join(
            f"  {name}: {{ code: 0x{s['code']:X}, rgb: {json.dumps(s['rgb'])}, alpha: '{s['alpha']}' }},\n" for name, s in stages.items()
        )
        + "} as const satisfies Record<string, { code: number; rgb: readonly [number, number, number]; alpha: string }>;\n"
    )
    print(f"{OUT}: {len(stages)} stages, {W}x{H}, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
